#!/usr/bin/env bash

###############################################################################
# Compose Provider
###############################################################################

###############################################################################
# Compose File
###############################################################################

compose_file() {

    echo "${PROJECT_ROOT}/docker-compose.yml"

}

###############################################################################
# Services
###############################################################################

compose_services() {

    docker compose \
        -f "$(compose_file)" \
        config \
        --services

}
