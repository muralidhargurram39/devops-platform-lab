#!/usr/bin/env bash

###############################################################################
# Platform Inventory
###############################################################################

###############################################################################
# Inventory Directory
###############################################################################

inventory_dir() {

    echo "${PROJECT_ROOT}/.platform/inventory"

}

###############################################################################
# Initialize Inventory
###############################################################################

inventory_init() {

    mkdir -p "$(inventory_dir)"

}

###############################################################################
# Inventory Exists
###############################################################################

inventory_exists() {

    [[ -d "$(inventory_dir)" ]]

}

###############################################################################
# Refresh Inventory
###############################################################################

inventory_refresh() {

    inventory_init

    compose_services > "$(inventory_dir)/tools"

}

###############################################################################
# Inventory Tools
###############################################################################

inventory_tools() {

    cat "$(inventory_dir)/tools"

}


