###############################################################################
# Timestamp
###############################################################################

timestamp() {

    date "+%Y-%m-%d %H:%M:%S"

}

###############################################################################
# Logging
###############################################################################

log_info() {

    printf "[%s] INFO: %s\n" "$(timestamp)" "$1"

}

log_success() {

    printf "[%s] SUCCESS: %s\n" "$(timestamp)" "$1"

}

log_warning() {

    printf "[%s] WARNING: %s\n" "$(timestamp)" "$1"

}

log_error() {

    printf "[%s] ERROR: %s\n" "$(timestamp)" "$1"

}

###############################################################################
# Command Execution
###############################################################################

run() {

    log_info "$*"

    "$@"

}

###############################################################################
# Exit Helper
###############################################################################

die() {

    log_error "$1"

    exit 1

}
