#!/usr/bin/env bash
#
# =============================================================================
# DevOps Lab Platform
# File    : common.sh
# Purpose : Common helper functions.
# =============================================================================

###############################################################################
# Source Guard
###############################################################################

[[ -n "${DEVOPS_COMMON_LOADED:-}" ]] && return 0
readonly DEVOPS_COMMON_LOADED=1

###############################################################################
# Timestamp
###############################################################################

timestamp() {

    date "+%Y-%m-%d %H:%M:%S"

}

###############################################################################
# Logging
###############################################################################

log_info() {

    printf "[%s] INFO: %s\n" "$(timestamp)" "$1"

}

log_success() {

    printf "[%s] SUCCESS: %s\n" "$(timestamp)" "$1"

}

log_warning() {

    printf "[%s] WARNING: %s\n" "$(timestamp)" "$1"

}

log_error() {

    printf "[%s] ERROR: %s\n" "$(timestamp)" "$1"

}

###############################################################################
# Command Execution
###############################################################################

run() {

    log_info "$*"

    "$@"

}

###############################################################################
# Exit Helper
###############################################################################
die() {

    local message="$1"
    local exit_code="${2:-1}"

    log_error "$message"

    print_error "$message"

    exit "$exit_code"

}
