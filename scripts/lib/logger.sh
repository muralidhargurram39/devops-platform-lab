#!/usr/bin/env bash
#
###############################################################################
# DevOps Lab Platform
# File    : logger.sh
# Purpose : Logging Library
###############################################################################

###############################################################################
# Source Guard
###############################################################################

[[ -n "${DEVOPS_LOGGER_LOADED:-}" ]] && return 0
readonly DEVOPS_LOGGER_LOADED=1

###############################################################################
# Log File
###############################################################################

readonly LOG_FILE="${LOGS_DIR}/platform.log"

###############################################################################
# Private Helpers
###############################################################################

_ensure_log_directory() {

    mkdir -p "${LOGS_DIR}"

}

_log() {

    _ensure_log_directory

    local level="$1"
    shift

    printf "[%s] %-5s %s\n" \
        "$(date '+%Y-%m-%d %H:%M:%S')" \
        "$level" \
        "$*" \
        >> "${LOG_FILE}"

}

###############################################################################
# Public API
###############################################################################

log_info() {

    _log INFO "$@"

}

log_warn() {

    _log WARN "$@"

}

log_error() {

    _log ERROR "$@"

}

log_debug() {

    _log DEBUG "$@"

}
