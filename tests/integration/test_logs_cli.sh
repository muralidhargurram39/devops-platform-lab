#!/usr/bin/env bash

set -Eeuo pipefail

SCRIPT_DIR="$(
    cd "$(dirname "${BASH_SOURCE[0]}")" &&
    pwd
)"

PROJECT_ROOT="$(
    cd "$SCRIPT_DIR/../.." &&
    pwd
)"

source "$PROJECT_ROOT/tests/test_common.sh"

PLATFORM="$PROJECT_ROOT/scripts/platform"

###############################################################################
# Default Logs
###############################################################################

"$PLATFORM" logs >/dev/null

assert_equals \
    0 \
    $? \
    "CLI logs"

###############################################################################
# Jenkins Logs
###############################################################################

"$PLATFORM" logs jenkins >/dev/null

assert_equals \
    0 \
    $? \
    "CLI logs jenkins"

###############################################################################
# Tail
###############################################################################

"$PLATFORM" logs --tail 100 >/dev/null

assert_equals \
    0 \
    $? \
    "CLI logs --tail"

###############################################################################
# Since
###############################################################################

"$PLATFORM" logs --since 30m >/dev/null

assert_equals \
    0 \
    $? \
    "CLI logs --since"

###############################################################################
# Invalid Service
###############################################################################

"$PLATFORM" logs invalid >/dev/null 2>&1

assert_equals \
    1 \
    $? \
    "CLI invalid service"

###############################################################################
# Invalid Tail
###############################################################################

"$PLATFORM" logs --tail abc >/dev/null 2>&1

assert_equals \
    1 \
    $? \
    "CLI invalid tail"

###############################################################################
# Invalid Since
###############################################################################

"$PLATFORM" logs --since xyz >/dev/null 2>&1

assert_equals \
    1 \
    $? \
    "CLI invalid since"

###############################################################################
# Summary
###############################################################################

print_summary
